import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:1400,height:900} })).newPage();
await p.goto("http://localhost:3000/login");
await p.locator("input").nth(0).fill("quetta_admin");
await p.locator("input").nth(1).fill("city12345");
await p.getByRole("button", { name: /sign in/i }).click();
await p.waitForURL("**/dashboard", { timeout: 30000 });
await p.goto("http://localhost:3000/payments", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(6000);
const rows = async () => await p.locator("tbody tr").count();
console.log("A) all dates            -> rows:", await rows());
await p.getByRole("button", { name: /^filters$/i }).click();
await p.waitForTimeout(600);
const sel = p.locator('select[aria-label="Date range preset"]');
console.log("B) preset options       :", JSON.stringify(await sel.locator("option").allTextContents()));
await sel.selectOption("all"); await p.waitForTimeout(2000);
console.log("C) after 'All dates'    -> rows:", await rows());
await sel.selectOption("custom"); await p.waitForTimeout(800);
const d = p.locator('input[type="date"]');
console.log("D) date inputs visible  :", await d.count());
await d.nth(0).fill("2026-10-02"); await p.waitForTimeout(1800);
await d.nth(1).fill("2026-10-02"); await p.waitForTimeout(2200);
console.log("E) custom 10-02..10-02  -> rows:", await rows(), "(expect 2)");
await d.nth(1).fill("2026-10-03"); await p.waitForTimeout(2200);
console.log("F) custom 10-02..10-03  -> rows:", await rows(), "(expect 4)");
const txt = await p.locator("body").innerText();
console.log("G) page text sample     :", JSON.stringify(txt.slice(0,180).replace(/\s+/g," ")));
await b.close();
